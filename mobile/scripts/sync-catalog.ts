/**
 * Snapshot of the web app's profile + search catalog for the native app, and
 * the web's pure profile rules copied in beside it.
 *
 * The web keeps one source of truth for what a profile asks and how it is
 * answered — `lib/profile/fields.ts` (the fields), `fieldGroups.ts` (how a
 * person groups them), `quickPicks.ts` (the tap-first answers) and
 * `lib/discovery/contract.ts` (the search filters). The app renders the same
 * catalog instead of keeping a second copy by hand: this script serialises it
 * to `src/catalog/catalog.generated.json`, which the app bundles.
 *
 * The rules that *judge* answers are code, not data, so they are copied as
 * code (`VENDORED` below): readiness (what counts as a valid value, the eight
 * a live profile needs), the password policy, and the whole of `/bolo`'s pure
 * logic — the draft's normalisation and `acceptAnswers`, the question ladder
 * and its chips, Grio's brief, the mic gate. Each copy is the web file with
 * only its import paths rewritten, so the app and the server accept exactly
 * the same answers. Nothing is edited by hand on this side.
 *
 * Grio's contract travels the same way: the action catalog, its markers and
 * their parser, and the concierge response shapes (`src/shared/grio/`), plus
 * the Marriage Intelligence questions a `<<<LEARN:>>>` card asks
 * (`src/catalog/grio.generated.json`). The app is a surface over the web's
 * Grio brain; its buttons and their wording are the web catalog's.
 *
 * Run from the repository root after any catalog or rule change:
 *
 *   npx tsx mobile/scripts/sync-catalog.ts          # write the snapshot + copies
 *   npx tsx mobile/scripts/sync-catalog.ts --check  # exit 1 if any is stale
 *
 * The server stays the authority either way — `/api/profile/save-draft` and
 * `/api/bolo/complete` re-validate every value against the live catalog — so a
 * stale copy can at worst offer an outdated option, never store an invalid one.
 */
