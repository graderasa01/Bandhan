/**
 * Two web modules the app keeps in one place (`./fields` and `./stages` are
 * both `~/catalog/fields`) would leave two imports of the same module behind.
 * Single-line named imports of one module are folded into the first of them
 * (`import type { X }` becoming `type X`), so a copy reads as if it were
 * written here.
 */
function foldDuplicateImports(code: string): string {
  const NAMED = /^import (type )?\{ ([^}]+) \} from "([^"]+)";$/;
  const lines = code.split("\n");
  const first = new Map<string, number>();
  const names = new Map<string, string[]>();
  const drop = new Set<number>();
  lines.forEach((line, i) => {
    const m = NAMED.exec(line);
    if (!m) return;
    const [, typeOnly, list, spec] = m;
    const parts = list!.split(",").map((n) => n.trim()).filter(Boolean).map((n) => (typeOnly && !n.startsWith("type ") ? `type ${n}` : n));
    if (first.has(spec!)) drop.add(i);
    else first.set(spec!, i);
    names.set(spec!, [...(names.get(spec!) ?? []), ...parts]);
  });
  if (drop.size === 0) return code;
  for (const [spec, i] of first) {
    const all = [...new Set(names.get(spec)!)];
    const allTypes = all.every((n) => n.startsWith("type "));
    lines[i] = allTypes
      ? `import type { ${all.map((n) => n.slice(5)).join(", ")} } from "${spec}";`
      : `import { ${all.join(", ")} } from "${spec}";`;
  }
  return lines.filter((_, i) => !drop.has(i)).join("\n");
}

function vendor(from: string): string {
  const source = readFileSync(path.join(REPO, from), "utf8").replace(/\r\n/g, "\n");
  const allowed = IMPORT_MAP[from] ?? {};
  const body = foldDuplicateImports(
    source
      .replace(/^"use client";\n+/, "")
      // Import and re-export statements only — a line that *starts* one, or the
      // `} from "…"` closing a multi-line one. Prose in a comment ("proposed
      // from "one message to one match"") is not an import.
      .replace(/^((?:import|export)\b[^\n]*?\bfrom\s+|\}\s*from\s+|import\s+)(["'])([^"']+)\2/gm, (whole, lead: string, quote: string, spec: string) => {
        const target = allowed[spec];
        if (!target) throw new Error(`${from} imports "${spec}", which the app has no copy of — add it to IMPORT_MAP.`);
        return `${lead}${quote}${target}${quote}`;
      }),
  );
  return (
    `// GENERATED from ${from} by mobile/scripts/sync-catalog.ts — do not edit.\n` +
    `// The web file is the one source of truth: change it there, then run\n` +
    `// \`npm run sync-catalog\` in mobile/. \`npm run check-catalog\` fails on drift.\n\n` +
    body
  );
}

const outputs: Array<{ file: string; content: string }> = [
  { file: OUT, content: json },
  { file: GRIO_OUT, content: grioJson },
  ...VENDORED.map(({ from, to }) => ({ file: path.join(REPO, to), content: vendor(from) })),
];

if (process.argv.includes("--check")) {
  const stale = outputs.filter(({ file, content }) => {
    try {
      return readFileSync(file, "utf8").replace(/\r\n/g, "\n") !== content;
    } catch {
      return true; // Missing counts as stale.
    }
  });
  if (stale.length > 0) {
    for (const { file } of stale) console.error(`stale: ${path.relative(process.cwd(), file)}`);
    console.error("Run: npx tsx mobile/scripts/sync-catalog.ts");
    process.exit(1);
  }
  console.log(`catalog.generated.json, grio.generated.json and ${VENDORED.length} shared rule files are up to date.`);
} else {
  for (const { file, content } of outputs) {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
  console.log(
    `Wrote ${path.relative(process.cwd(), OUT)} — ${snapshot.fields.length} fields, ` +
      `${snapshot.discover.filters.length} filters, ${snapshot.places.length} states — ` +
      `${path.relative(process.cwd(), GRIO_OUT)} — ${grioSnapshot.learnQuestions.length} learn questions — ` +
      `and ${VENDORED.length} shared rule files.`,
  );
}
